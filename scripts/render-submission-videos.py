"""Prepare honest 1080p video frames, English captions and timed narration.

Requires Pillow, installed Windows Segoe fonts, and WAVs generated by
synthesize-submission-narration.ps1. Encoding is handled by the companion
Chrome MediaRecorder script; no project dependency or wallet is used.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import wave

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
WIDTH, HEIGHT = 1920, 1080
BACKGROUND = "#10251d"
PANEL = "#19392c"
ACCENT = "#a9dbb8"
INK = "#f4f2e8"
MUTED = "#b8c7bd"
GOLD = "#e8cf83"
FONT_ROOT = Path("C:/Windows/Fonts")


def font(size: int, bold: bool = False, mono: bool = False):
    name = "consola.ttf" if mono else "segoeuib.ttf" if bold else "segoeui.ttf"
    return ImageFont.truetype(str(FONT_ROOT / name), size)


def wrapped(draw, text: str, face, width: int) -> list[str]:
    lines, current = [], ""
    for word in text.split():
        candidate = f"{current} {word}".strip()
        if current and draw.textlength(candidate, font=face) > width:
            lines.append(current)
            current = word
        else:
            current = candidate
    return lines + ([current] if current else [])


def paragraph(draw, text, xy, size=40, width=1700, fill=INK, bold=False, gap=12):
    face = font(size, bold)
    lines = wrapped(draw, text, face, width)
    for index, line in enumerate(lines):
        draw.text((xy[0], xy[1] + index * (size + gap)), line, font=face, fill=fill)
    return len(lines) * (size + gap)


def caption_text(text: str) -> str:
    replacements = {
        "Lifecycle KASE": "LifecycleKASE", "K Z T test": "KZT-Test",
        "SHA two fifty six": "SHA-256", "K Y C": "KYC", "C sharp": "C#",
        "full stack": "full-stack", "post issuance": "post-issuance",
        "on chain": "on-chain", "public network": "public-network",
    }
    for old, new in replacements.items():
        text = text.replace(old, new)
    return text


def frame(scene: dict, caption: str, number: int, total: int, runtime: dict) -> Image.Image:
    image = Image.new("RGB", (WIDTH, HEIGHT), BACKGROUND)
    draw = ImageDraw.Draw(image)
    draw.rectangle((0, 0, 12, HEIGHT), fill=ACCENT)
    draw.text((64, 28), scene["eyebrow"], font=font(26, True), fill=ACCENT)
    draw.text((1854, 30), f"{number:02d}/{total:02d}", font=font(24), anchor="ra", fill=MUTED)
    paragraph(draw, scene["title"], (64, 71), size=45, bold=True, width=1760)
    kind = scene["kind"]
    if kind == "footage":
        draw.rounded_rectangle((64, 157, 1856, 875), 12, fill=PANEL)
        draw.text((64, 887), "Recorded running application · walletless QA · all financial actions are simulated", font=font(24), fill=MUTED)
    elif kind == "ui":
        source = Image.open(ROOT / scene["image"]).convert("RGB")
        if scene.get("crop"):
            source = source.crop(tuple(scene["crop"]))
        source.thumbnail((1792, 718), Image.Resampling.LANCZOS)
        x, y = (WIDTH - source.width) // 2, 157 + (718 - source.height) // 2
        draw.rounded_rectangle((x - 8, y - 8, x + source.width + 8, y + source.height + 8), 12, fill=ACCENT)
        image.paste(source, (x, y))
        draw.text((64, 887), "Saved synthetic interface fixture · no financial transaction is performed in this video", font=font(24), fill=MUTED)
    elif kind == "title":
        draw.rounded_rectangle((64, 183, 1856, 872), 24, fill=PANEL)
        draw.text((121, 307), scene["display"][0], font=font(128, True), fill=INK)
        paragraph(draw, scene["display"][1], (128, 500), size=56, width=1600, fill=ACCENT)
        draw.text((128, 744), "English submission video · 12 October 2026", font=font(32), fill=MUTED)
    elif kind == "workflow":
        for index, label in enumerate(scene["display"]):
            column, row = index % 3, index // 3
            x, y = 64 + column * 607, 213 + row * 285
            draw.rounded_rectangle((x, y, x + 568, y + 230), 20, fill=PANEL, outline="#41604b", width=2)
            draw.text((x + 28, y + 24), f"0{index + 1}", font=font(42, True), fill=GOLD)
            paragraph(draw, label, (x + 28, y + 100), 40, 510, bold=True)
        draw.text((64, 817), "An approval or HTTP response is not settlement. Finalized effects are reconciled.", font=font(30), fill=MUTED)
    elif kind == "results":
        labels = ["Coupon", "20% partial", "Exact target 8", "Maturity"]
        for index, action in enumerate(runtime["actions"]):
            x, y = 64 + (index % 2) * 920, 189 + (index // 2) * 321
            draw.rounded_rectangle((x, y, x + 876, y + 281), 22, fill=PANEL)
            draw.text((x + 34, y + 24), labels[index], font=font(38, True), fill=INK)
            amount = int(action["amountMinor"]) // 1_000_000
            draw.text((x + 34, y + 87), f"{amount:,}", font=font(76, True), fill=GOLD)
            draw.text((x + 34, y + 198), f"KZT-Test  ·  supply {action['supplyBefore']} → {action['supplyAfter']}", font=font(30), fill=ACCENT)
        draw.text((64, 872), "Recorded disposable test-chain effects · KZT-Test and eligibility are simulated", font=font(26), fill=MUTED)
    elif kind == "receipts":
        names = ["Coupon", "20% partial", "Exact target 8", "Maturity"]
        for index, action in enumerate(runtime["actions"]):
            y = 179 + index * 168
            draw.rounded_rectangle((64, y, 1856, y + 139), 16, fill=PANEL)
            draw.text((90, y + 16), f"{names[index]} · SHA-256 of original canonical JSON", font=font(31, True), fill=ACCENT)
            draw.text((90, y + 70), action["receiptHash"], font=font(32, mono=True), fill=INK)
        draw.text((64, 873), "Hashes copied from the completed controlled-workflow runtime; saved consistency is not a new RPC query.", font=font(23), fill=MUTED)
    else:
        lines = scene.get("display", [])
        for index, text in enumerate(lines):
            y = 208 + index * 198
            draw.rounded_rectangle((64, y, 1856, y + 167), 20, fill=PANEL)
            draw.text((91, y + 32), f"0{index + 1}", font=font(42, True), fill=GOLD)
            paragraph(draw, text, (196, y + 32), 44, 1580, fill=INK, bold=index == 0)
        if kind == "closing":
            draw.text((64, 867), "LifecycleKASE is not affiliated with or approved by KASE.", font=font(27), fill=MUTED)
    draw.rectangle((0, 924, WIDTH, HEIGHT), fill="#09160f")
    lines = wrapped(draw, caption, font(37), 1768)
    if len(lines) > 3:
        raise ValueError(f"Caption needs more than three lines: {caption}")
    top = 928 + max(0, (144 - len(lines) * 45) // 2)
    for index, line in enumerate(lines):
        draw.text((WIDTH // 2, top + index * 45), line, font=font(37), fill=INK, anchor="ma")
    return image


def srt_time(seconds: float) -> str:
    milliseconds = round(seconds * 1000)
    hours, milliseconds = divmod(milliseconds, 3_600_000)
    minutes, milliseconds = divmod(milliseconds, 60_000)
    seconds, milliseconds = divmod(milliseconds, 1000)
    return f"{hours:02}:{minutes:02}:{seconds:02},{milliseconds:03}"


def prepare(storyboard: Path, output: Path):
    story = json.loads(storyboard.read_text(encoding="utf-8"))
    runtime = json.loads((ROOT / story["runtime"]).read_text(encoding="utf-8"))
    expected = [("1750000000", "35", "35"), ("7000000000", "35", "28"), ("8000000000", "28", "20"), ("21000000000", "20", "0")]
    actual = [(a["amountMinor"], a["supplyBefore"], a["supplyAfter"]) for a in runtime["actions"]]
    if runtime["scope"] != "DISPOSABLE_LOCALNET" or actual != expected:
        raise ValueError("Storyboard metrics must be reviewed for a changed runtime")
    for action in runtime["actions"]:
        if hashlib.sha256(action["canonicalJson"].encode()).hexdigest() != action["receiptHash"]:
            raise ValueError("Original canonical receipt hash mismatch")
    output.mkdir(parents=True, exist_ok=True)
    videos = []
    for video in story["videos"]:
        asset_directory = output / video["id"]
        asset_directory.mkdir(exist_ok=True)
        entries, params, spoken_bytes = [], None, bytearray()
        cursor = 0.0
        for scene_index, scene in enumerate(video["scenes"]):
            for sentence_index, sentence in enumerate(scene["sentences"]):
                wav_path = output / "narration" / f"{video['id']}-{scene_index:02}-{sentence_index:02}.wav"
                with wave.open(str(wav_path), "rb") as audio:
                    current = (audio.getnchannels(), audio.getsampwidth(), audio.getframerate())
                    if params is not None and current != params:
                        raise ValueError("Narration WAV formats differ")
                    params = current
                    wav_bytes = audio.readframes(audio.getnframes())
                    duration = audio.getnframes() / current[2]
                pause = 0.45 if sentence_index < len(scene["sentences"]) - 1 else 0.75
                title = caption_text(sentence)
                name = f"frame-{scene_index:02}-{sentence_index:02}.png"
                frame(scene, title, scene_index + 1, len(video["scenes"]), runtime).save(asset_directory / name)
                entries.append({"start": round(cursor, 6), "duration": round(duration + pause, 6), "caption": title, "frame": f"{video['id']}/{name}", "scene": scene_index + 1})
                spoken_bytes.extend(wav_bytes)
                spoken_bytes.extend(bytes(round(pause * params[2]) * params[0] * params[1]))
                cursor += duration + pause
        if cursor < video["minimumSeconds"]:
            padding = video["minimumSeconds"] - cursor
            entries[-1]["duration"] += padding
            spoken_bytes.extend(bytes(round(padding * params[2]) * params[0] * params[1]))
            cursor += padding
        if cursor > video["maximumSeconds"]:
            raise ValueError(f"{video['id']} is {cursor:.2f}s; use a faster narration rate or shorten the script")
        wav_output = output / f"lifecyclekase-{video['id']}-en.wav"
        with wave.open(str(wav_output), "wb") as audio:
            audio.setnchannels(params[0])
            audio.setsampwidth(params[1])
            audio.setframerate(params[2])
            audio.writeframes(spoken_bytes)
        subtitles = "\n\n".join(f"{index + 1}\n{srt_time(entry['start'])} --> {srt_time(entry['start'] + entry['duration'])}\n{entry['caption']}" for index, entry in enumerate(entries)) + "\n"
        (output / f"lifecyclekase-{video['id']}-en.srt").write_text(subtitles, encoding="utf-8")
        (output / f"lifecyclekase-{video['id']}-en.txt").write_text("\n\n".join(entry["caption"] for entry in entries) + "\n", encoding="utf-8")
        for entry in entries:
            entry["footage"] = video["scenes"][entry["scene"] - 1]["kind"] == "footage"
        videos.append({"id": video["id"], "title": video["title"], "duration": round(cursor, 6), "audio": wav_output.name, "output": f"lifecyclekase-{video['id']}-en.mp4", "footage": "qa-interactive-en.webm" if video["id"] == "demo" else None, "entries": entries})
        print(f"Prepared {video['id']}: {cursor:.3f}s, {len(entries)} captioned frames")
    (output / "render-manifest.json").write_text(json.dumps({"width": WIDTH, "height": HEIGHT, "fps": 24, "storyboard": str(storyboard.relative_to(ROOT)), "sourceCommit": story["sourceCommit"], "runtime": story["runtime"], "videos": videos}, indent=2), encoding="utf-8")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--storyboard", type=Path, default=ROOT / "docs/submission/video-storyboard-2026-10-12.json")
    parser.add_argument("--output", type=Path, default=ROOT / ".local-submission-media-20261012")
    arguments = parser.parse_args()
    prepare(arguments.storyboard.resolve(), arguments.output.resolve())
